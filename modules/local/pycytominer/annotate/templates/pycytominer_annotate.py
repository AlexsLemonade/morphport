#!/usr/bin/env python3
"""
Nextflow template script to annotate a per-plate parquet file with platemap metadata using pycytominer.
If the plate is split across multiple parquet files, they are concatenated before annotation.
The platemap is expected to be a comma-delimited (.csv) or tab-delimited (.tsv or .txt) file
with a column matching the well identifier in the parquet metadata (e.g. Metadata_Well).

Downstream steps identify cells by Metadata_Plate, Metadata_Well, Metadata_ImageNumber, and Metadata_ObjectNumber.
Profiles generated by some CytoTable settings name some of these differently, so before annotation each missing identifier column
is renamed from its alternative name if present (see IDENTIFIER_ALTERNATIVES), e.g., 'Image_Metadata_Well'
from the CytoTable pycytominer preset is renamed to 'Metadata_Well'.
The annotated output is written in parquet format.

All platemap columns (including plate_map_name, if present) except the well column are added to the parquet file
by pycytominer annotate as 'Metadata_'-prefixed columns.
We also ensure that all columns specified in the meta.platemap_columns variable from Nextflow are present.
Any listed metadata column absent from the platemap is filled with '_Absent_' to ensure it is available for downstream steps.
Platemap values are read as literal text with whitespace stripped; blank values are filled with '_NA_' before merging.

Profiles are joined to the platemap by well, matching values exactly (after the platemap's whitespace is stripped).
Cells in unmatched wells (wells with profiles but no platemap row, including cells with no well value)
are dropped by the join; they are reported in the warnings file with the number of cells dropped from each well.
If no profile well matches the platemap (e.g. A1 vs A01), the process fails.

After annotation, metadata columns that duplicate each other are checked:
- Columns whose names differ only by the _platemap suffix pycytominer adds on name collisions,
  the numeric suffix (_1, _2, ...) DuckDB adds to repeated names in CytoTable joins,
  or a compartment prefix (e.g. Image_Metadata_Well vs Metadata_Well) are compared as text.
  Identical columns are reduced to one column with the plain Metadata_ name;
  columns that agree except for missing values are coalesced into the plain name;
  conflicting columns are all kept, so _platemap columns remain only in that case.
- Non-constant metadata columns with identical values but unrelated names are reported only.
  Conflicts, coalesced columns, and identical-value columns are written to a warnings file
  so Nextflow can surface them in the run log.
"""

import hashlib
import sys
import warnings
from importlib.metadata import version

import pandas as pd
import pycytominer

# pyarrow-backed DataFrames trigger pandas' fragmentation warning; quiet it.
warnings.filterwarnings("ignore", category=pd.errors.PerformanceWarning)


def write_versions(task_process: str):
    with open("versions.yml", "w") as f:
        f.write(f'"{task_process}":\\n')
        f.write(f"    python: {sys.version.split()[0]}\\n")
        f.write(f"    pycytominer: {version('pycytominer')}\\n")
        f.write(f"    pandas: {version('pandas')}\\n")
        f.write(f"    pyarrow: {version('pyarrow')}\\n")


# Alternative names for the identifier columns used downstream, mapped to the standard name each replaces,
# from CytoTable presets other than cpg0016 JUMP (e.g. cellprofiler_sqlite_pycytominer).
IDENTIFIER_ALTERNATIVES = {
    "Image_Metadata_Plate": "Metadata_Plate",
    "Image_Metadata_Well": "Metadata_Well",
    "Metadata_Cells_Number_Object_Number": "Metadata_ObjectNumber",
}


def standardize_identifier_columns(
    df: pd.DataFrame,
) -> tuple[pd.DataFrame, list[str]]:
    """
    Rename alternative identifier columns to the names used downstream (see IDENTIFIER_ALTERNATIVES).
    A column is renamed only when the standard name is missing.
    Returns the updated DataFrame and a list of messages describing the renamed columns.
    """
    renames = {
        col: IDENTIFIER_ALTERNATIVES[col]
        for col in df.columns
        if col in IDENTIFIER_ALTERNATIVES
        and IDENTIFIER_ALTERNATIVES[col] not in df.columns
    }
    messages = [f"Renamed {old} to {new}." for old, new in renames.items()]
    return df.rename(columns=renames), messages


def add_metadata_prefix(col: str) -> str:
    """Add the Metadata_ prefix to a column name if it is not already present (as addMetadataPrefix in Nextflow)."""
    return col if col.startswith("Metadata_") else "Metadata_" + col


def find_platemap_column(columns: list[str], column: str) -> str | None:
    """
    Find a platemap column by name, with or without the Metadata_ prefix on either side,
    as the create_analysis_groups subworkflow does (e.g. 'Well' matches a 'Metadata_Well' header).
    Returns the platemap's own column name, or None if there is no match.
    Nextflow rejects platemaps with two headers that are the same once prefixed, so there is at most one match.
    """
    for col in columns:
        if add_metadata_prefix(col) == add_metadata_prefix(column):
            return col
    return None


def count_unmatched_wells(
    profile_wells: pd.Series, platemap_wells: pd.Series
) -> dict[str, int]:
    """
    Count the cells in each profile well that has no platemap row.
    Wells are compared as text, exactly; cells with no well value are counted under '(missing)'.
    Returns a dict of well to cell count, with wells sorted and '(missing)' last.
    """
    platemap_well_set = set(platemap_wells)
    counts = profile_wells.astype("string[pyarrow]").value_counts(dropna=False)
    unmatched = {}
    n_missing = 0
    for well, n_cells in counts.items():
        if pd.isna(well):
            n_missing = int(n_cells)
        elif well not in platemap_well_set:
            unmatched[well] = int(n_cells)
    unmatched = dict(sorted(unmatched.items()))
    if n_missing > 0:
        unmatched["(missing)"] = n_missing
    return unmatched


def format_unmatched_wells(unmatched: dict[str, int]) -> str:
    """Format the unmatched wells and their cell counts as a warning message."""
    wells = []
    for well, n_cells in unmatched.items():
        cell_label = "cell" if n_cells == 1 else "cells"
        wells.append(f"{well} ({n_cells} {cell_label})")
    return (
        "Wells with profiles but no platemap row were dropped: "
        + ", ".join(wells)
        + "."
    )


def example_values(values: pd.Series, n: int = 5) -> str:
    """Return the first n distinct non-missing values, sorted, as a comma-separated string."""
    distinct = sorted(values.dropna().astype(str).unique())
    return ", ".join(distinct[:n])


def is_metadata_column(col: str) -> bool:
    return col.startswith("Metadata_") or "_Metadata_" in col


def normalize_metadata_name(col: str, all_columns: set) -> str:
    """
    Normalize a metadata column name for duplicate detection.
    The _platemap suffix added by pycytominer.annotate on name collisions is stripped.
    A numeric suffix (_1, _2, ...) added by DuckDB to repeated names in CytoTable joins
    is stripped only when the base name is also present, so names like Metadata_Site_1 are kept.
    Then any compartment prefix before Metadata_ is removed.
    """
    col = col.removesuffix("_platemap")
    base, _, number = col.rpartition("_")
    if number.isdigit() and base in all_columns:
        col = base
    if not col.startswith("Metadata_"):
        col = "Metadata_" + col.split("_Metadata_", 1)[1]
    return col


def resolve_duplicate_metadata(df: pd.DataFrame) -> tuple[pd.DataFrame, list[str]]:
    """
    Resolve metadata columns that share a normalized name.
    Values are compared as text so that e.g. platemap '24' matches a numeric 24.
    Returns the updated DataFrame and a list of warning messages.
    """
    messages = []
    all_columns = set(df.columns)
    groups = {}
    for col in df.columns:
        if is_metadata_column(col):
            groups.setdefault(normalize_metadata_name(col, all_columns), []).append(col)

    for name, cols in groups.items():
        if len(cols) < 2:
            continue
        # keep the column that already has the normalized name, if any
        keep = name if name in cols else cols[0]
        others = [col for col in cols if col != keep]

        combined = df[keep].astype("string[pyarrow]")
        identical = True
        conflict = False
        for col in others:
            values = df[col].astype("string[pyarrow]")
            both = combined.notna() & values.notna()
            if not (combined[both] == values[both]).all():
                conflict = True
                break
            identical = identical and combined.equals(values)
            combined = combined.combine_first(values)

        if conflict:
            messages.append(
                f"Columns {', '.join(cols)} have conflicting values; all were kept as is."
            )
            continue
        if identical:
            print(
                f"Dropping {', '.join(others)}: identical to {keep}.", file=sys.stderr
            )
        else:
            messages.append(
                f"Columns {', '.join(cols)} differ only in missing values; coalesced into {name}."
            )
            # restore the original type of the kept column where possible
            try:
                df[keep] = combined.astype(df[keep].dtype)
            except (TypeError, ValueError):
                df[keep] = combined
        df = df.drop(columns=others).rename(columns={keep: name})

    return df, messages


def find_identical_metadata(df: pd.DataFrame) -> list[str]:
    """
    Find non-constant metadata columns with identical values but different names.
    Constant columns are skipped, as plate-level values match each other by coincidence.
    Each column is hashed once; columns with matching hashes are confirmed with equals().
    Returns a list of warning messages; no columns are dropped.
    """
    by_hash = {}
    for col in df.columns:
        if not is_metadata_column(col) or df[col].nunique(dropna=False) <= 1:
            continue
        values = df[col].astype("string[pyarrow]")
        row_hashes = pd.util.hash_pandas_object(values, index=False).to_numpy()
        key = hashlib.sha256(row_hashes.tobytes()).hexdigest()
        by_hash.setdefault(key, []).append((col, values))

    messages = []
    for candidates in by_hash.values():
        first_col, first_values = candidates[0]
        matches = [col for col, values in candidates[1:] if first_values.equals(values)]
        if matches:
            messages.append(
                f"Columns {', '.join([first_col] + matches)} have identical values."
            )
    return messages


def main():
    # capture input variables from Nextflow
    platemap_file = "${platemap_file}"
    platemap_well_column = "${platemap_well_column}"
    # directory where Nextflow stages the input parquet file(s) (stageAs in main.nf)
    parquet_dir = "input_parquet"
    plate_id = "${meta.plate_id}"
    task_process = "${task.process}"
    # merge the metadata column list during import from Nextflow to make them a string
    platemap_columns = "${meta.platemap_columns.join(',')}"

    # Read every platemap value as literal text so values match what Nextflow reads from the
    # same file when predicting analysis groups (enumeratePlatemapPartitionValues): no type inference
    # (e.g. '010' stays '010', not 10.0), no NA-like strings ('NA', 'null') converted to nulls,
    # and surrounding whitespace stripped. Only blank cells become '_NA_'.
    # choose the delimiter by extension, matching platemapSeparator in Nextflow
    platemap_ext = platemap_file.rsplit(".", 1)[-1].lower()
    if platemap_ext == "csv":
        platemap_sep = ","
    elif platemap_ext in ("tsv", "txt"):
        platemap_sep = "\\t"
    else:
        raise ValueError(
            f"Platemap {platemap_file} must have a .csv, .tsv, or .txt extension."
        )
    platemap_df = pd.read_csv(
        platemap_file,
        sep=platemap_sep,
        encoding="utf-8-sig",
        dtype="string[pyarrow]",
        na_filter=False,
    )
    platemap_df.columns = [col.strip() for col in platemap_df.columns]
    platemap_df = (
        platemap_df.apply(lambda values: values.str.strip())
        # rows with missing trailing fields are filled with nulls despite na_filter=False
        .fillna("")
        .replace("", "_NA_")
    )

    # ensure all partition columns exist in the platemap before annotation,
    # either with raw names or without the Metadata_ prefix;
    # all will have the prefix added by pycytominer.annotate
    existing_cols = set(platemap_df.columns)
    for col in platemap_columns.split(","):
        if (
            col not in existing_cols
            and col.removeprefix("Metadata_") not in existing_cols
        ):
            platemap_df[col] = "_Absent_"
    platemap_df = platemap_df.astype("string[pyarrow]")

    # Read with pyarrow so null values are preserved through pycytominer.
    # Reading the directory combines split parquet files into a single table.
    profiles_df = pd.read_parquet(parquet_dir, dtype_backend="pyarrow")

    # use the standard names for identifier columns from other CytoTable presets
    profiles_df, rename_messages = standardize_identifier_columns(profiles_df)
    for message in rename_messages:
        print(message, file=sys.stderr)

    # check the well columns used for the join before annotating;
    # the platemap well column may be named with or without the Metadata_ prefix
    well_column = find_platemap_column(
        columns=platemap_df.columns, column=platemap_well_column
    )
    if well_column is None:
        print(
            f"The specified platemap_well_column '{platemap_well_column}' was not found in the platemap file.",
            file=sys.stderr,
        )
        sys.exit(1)
    if "Metadata_Well" not in profiles_df.columns:
        print(
            "The expected 'Metadata_Well' column or an accepted alternative was not found in the parquet file metadata.",
            file=sys.stderr,
        )
        sys.exit(1)

    # cells in wells with no platemap row are dropped by the join: report them,
    # and fail if no cells match, which usually means a different well format (e.g. A1 vs A01)
    messages = []
    unmatched = count_unmatched_wells(
        profile_wells=profiles_df["Metadata_Well"],
        platemap_wells=platemap_df[well_column],
    )
    n_unmatched_cells = sum(unmatched.values())
    if len(profiles_df) > 0 and n_unmatched_cells == len(profiles_df):
        print(
            f"No wells in the profiles match the platemap's '{well_column}' column.\\n"
            f"Profile wells include: {example_values(profiles_df['Metadata_Well'])}\\n"
            f"Platemap wells include: {example_values(platemap_df[well_column])}\\n"
            "Check that the well formats match and that the platemap is the right one for this plate.",
            file=sys.stderr,
        )
        sys.exit(1)
    if unmatched:
        messages.append(format_unmatched_wells(unmatched))

    annotated_df = pycytominer.annotate(
        profiles=profiles_df,
        platemap=platemap_df,
        # pycytominer adds the Metadata_ prefix to unprefixed platemap columns
        join_on=[add_metadata_prefix(well_column), "Metadata_Well"],
    )
    annotated_df, duplicate_messages = resolve_duplicate_metadata(annotated_df)
    messages = messages + duplicate_messages + find_identical_metadata(annotated_df)
    if messages:
        with open(f"{plate_id}_metadata_warnings.txt", "w") as f:
            for message in messages:
                print(f"WARNING: {message}", file=sys.stderr)
                f.write(f"{message}\\n")
    annotated_df.to_parquet(f"{plate_id}_annotated.parquet", index=False)

    write_versions(task_process)


if __name__ == "__main__":
    main()
